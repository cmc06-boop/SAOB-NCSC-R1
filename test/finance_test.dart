void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  late FinanceDatabase db;
  late FinanceStore store;
  BudgetRecord record({
    String code = '5020101000',
    int a = 100010,
    int o = 25005,
    int d = 10001,
    int? id,
    int? year,
    String program = 'GAS',
  }) => BudgetRecord(
    id: id,
    year: year ?? manilaNow().year,
    program: program,
    code: code,
    name: 'Office supplies',
    allotment: a,
    obligation: o,
    disbursement: d,
  );
  setUp(() {
    db = FinanceDatabase.open(path: ':memory:');
    store = FinanceStore(db);
    store.user = const LocalUser(1, 'AO', 'ao', 'Admin');
    db.connection.execute(
      "INSERT INTO programs(code,name,active) VALUES ('GAS','GAS',1),('ECA','ECA',1)",
    );
  });
  tearDown(() {
    store.dispose();
    db.close();
  });

  test('decimal input and totals preserve every cent', () {
    expect(parseCents('₱1,234.50'), 123450);
    expect(parseCents('0.1'), 10);
    expect(parseCents('0.001'), isNull);
    expect(parseCents('-1'), isNull);
    expect(parseCents('NaN'), isNull);
    expect(parseCents('', required: true), isNull);
    final t = Totals([
      record(a: 10, o: 5, d: 0),
      record(code: '5020102000', a: 20, o: 10, d: 5),
    ]);
    expect(t.allotment, 30);
    expect(t.balance, 15);
    expect(t.disbursement, 5);
    expect(rate(5, 0), '—');
  });
  test('Dart verifies the exact PBKDF2 hash generated by Python', () async {
    const stored =
        '00112233445566778899aabbccddeeff\$33105e1734d59772de932336f0e16525cecc97e440d3dffad93bfec66d9d4013';
    expect(await Passwords.verify('AOpassword2026', stored), isTrue);
    expect(await Passwords.verify('wrong password', stored), isFalse);
    expect(await Passwords.verify('anything', 'malformed'), isFalse);
  });
  test('duplicate saves leave data unchanged; amount cross-checks are not enforced', () {
    store.saveRecord(record());
    final before = db.rows('SELECT * FROM audit_log').length;
    expect(() => store.saveRecord(record()), throwsA(isA<FinanceError>()));
    expect(store.records(manilaNow().year).length, 1);
    expect(db.rows('SELECT * FROM audit_log').length, before);
    // Like Excel: obligation/disbursement may exceed allotment.
    store.saveRecord(record(code: '5020102000', o: 100011));
    store.saveRecord(record(code: '5020103000', a: 100, d: 25006));
    expect(store.records(manilaNow().year).length, 3);
    final row = store.records(manilaNow().year, query: '5020101000').single;
    store.saveRecord(record(id: row.id, o: 30000));
    expect(store.byId(row.id!)!.balance, 70010);
    expect(
      db
          .rows('SELECT detail FROM audit_log ORDER BY id DESC LIMIT 1')
          .first['detail'],
      contains('Obligation'),
    );
  });
  test('workbook import logs one audit for all programs', () {
    expect(
      store.importRecords([record()], updateExisting: true),
      1,
    );
    expect(
      store.importRecords([
        record(program: 'ECA', code: '5020102000'),
      ], updateExisting: true),
      1,
    );
    store.logWorkbookImport(
      filename: 'SAOB_2026.xlsx',
      year: manilaNow().year,
    );
    final detail =
        db
                .rows(
                  "SELECT detail FROM audit_log WHERE action='Imported' ORDER BY id DESC LIMIT 1",
                )
                .single['detail']
            as String;
    expect(detail, 'SAOB_2026.xlsx');
  });
  test('import is atomic and duplicate-safe; updates are explicit', () {
    // Excel import keeps obligation/allotment as-is even when obligation is higher.
    expect(
      store.importRecords([
        record(),
        record(code: '5020102000', o: 200000),
      ], updateExisting: true),
      2,
    );
    expect(store.records(manilaNow().year).length, 2);
    expect(
      () => store.importRecords([record(), record()], updateExisting: true),
      throwsA(isA<FinanceError>()),
    );
    expect(store.importRecords([record(o: 30000)], updateExisting: false), 0);
    expect(
      store.records(manilaNow().year, query: '5020101000').single.obligation,
      25005,
    );
    expect(store.importRecords([record(o: 30000)], updateExisting: true), 1);
    expect(store.importRecords([record(o: 30000)], updateExisting: true), 0);
  });
  test('inactive programs retain history and cannot receive new lines', () {
    store.saveRecord(record());
    final old = store.records(manilaNow().year).single;
    store.saveProgram(
      'GAS',
      'General Administration and Support',
      false,
      original: 'GAS',
    );
    expect(store.records(manilaNow().year).length, 1);
    expect(
      () => store.saveRecord(record(code: '5020102000')),
      throwsA(isA<FinanceError>()),
    );
    store.saveRecord(record(id: old.id, o: 30000));
    expect(store.byId(old.id!)!.obligation, 30000);
    store.saveProgram(
      'GASR1',
      'General Administration and Support',
      true,
      original: 'GAS',
    );
    expect(store.records(manilaNow().year, program: 'GASR1').length, 1);
  });
  test('permissions are enforced in the service, not only in menus', () {
    store.user = const LocalUser(2, 'Viewer', 'viewer', 'Viewer');
    expect(() => store.saveRecord(record()), throwsA(isA<FinanceError>()));
    expect(
      () => store.saveProgram('TEST', 'Test', true),
      throwsA(isA<FinanceError>()),
    );
    store.user = null;
    expect(
      () => store.importRecords([record()], updateExisting: true),
      throwsA(isA<FinanceError>()),
    );
  });
  test('new fiscal year is automatic and never copies balances', () {
    store.saveRecord(record());
    final current = manilaNow().year;
    db.ensureCurrentYear(today: DateTime(current + 1, 1, 1));
    expect(
      db.rows('SELECT year FROM fiscal_years WHERE active=1').single['year'],
      current + 1,
    );
    expect(
      db.rows('SELECT * FROM budget_records WHERE year=?', [current + 1]),
      isEmpty,
    );
    expect(
      db.rows('SELECT * FROM budget_records WHERE year=?', [current]).length,
      1,
    );
  });
  test('past fiscal years are read-only for encode, import, and delete', () {
    final past = manilaNow().year - 1;
    expect(
      () => store.saveRecord(record(year: past, code: '5020104000')),
      throwsA(
        isA<FinanceError>().having(
          (e) => e.message,
          'message',
          contains('current fiscal year'),
        ),
      ),
    );
    expect(
      () => store.importRecords([
        record(year: past, code: '5020105000'),
      ], updateExisting: true),
      throwsA(
        isA<FinanceError>().having(
          (e) => e.message,
          'message',
          contains('current fiscal year'),
        ),
      ),
    );
    db.connection.execute(
      "INSERT INTO budget_records(year,program,fund_source,code,name,allotment,obligation,disbursement,remarks) "
      "VALUES (?,?, 'CURRENT','5020106000','Past year line',100,10,5,'')",
      [past, 'GAS'],
    );
    final pastId =
        db.rows('SELECT id FROM budget_records WHERE code=?', [
              '5020106000',
            ]).single['id']
            as int;
    expect(
      () => store.deleteRecord(pastId),
      throwsA(
        isA<FinanceError>().having(
          (e) => e.message,
          'message',
          contains('current fiscal year'),
        ),
      ),
    );
    expect(store.byId(pastId), isNotNull);
  });
  test('Manila audit dates do not shift backward around midnight', () {
    db.connection.execute(
      "INSERT INTO audit_log(at,username,action,title,detail,year,program) VALUES ('2026-11-19T00:05:00+08:00','ao','Added','Test','',2026,'GAS')",
    );
    expect(
      store.auditRows(2026, from: '2026-11-19', through: '2026-11-19').length,
      1,
    );
    expect(
      store.auditRows(2026, from: '2026-11-18', through: '2026-11-18'),
      isEmpty,
    );
  });
  test(
    'Python SQLite and passwords migrate without altering the source, once',
    () async {
      final temp = Directory.systemTemp.createTempSync('ncsc-migration-');
      final original = File('test/fixtures/python_finance.sqlite')
          .readAsBytesSync();
      final source = File('${temp.path}/legacy.sqlite')
        ..writeAsBytesSync(original);
      final target = '${temp.path}/flutter.sqlite';
      var migrated = FinanceDatabase.open(
        path: target,
        legacyPath: source.path,
      );
      var service = FinanceStore(migrated);
      await service.signIn('ADMIN', 'admin');
      expect(service.user!.role, 'Admin');
      final r = service.records(2026).single;
      expect(r.allotment, 100010);
      expect(r.obligation, 25005);
      expect(r.disbursement, 10001);
      service.deleteRecord(r.id!);
      service.dispose();
      migrated.close();
      migrated = FinanceDatabase.open(path: target, legacyPath: source.path);
      service = FinanceStore(migrated);
      expect(service.records(2026), isEmpty); // No re-import on next launch.
      expect(source.readAsBytesSync(), original);
      service.dispose();
      migrated.close();
      temp.deleteSync(recursive: true);
    },
  );
  test('migration includes committed records still held in the SQLite WAL', () {
    final temp = Directory.systemTemp.createTempSync('ncsc-wal-');
    final sourcePath = '${temp.path}/python.sqlite';
    File('test/fixtures/python_finance.sqlite').copySync(sourcePath);
    final source = FinanceDatabase.open(path: sourcePath);
    source.connection.execute(
      "INSERT INTO budget_records(year,program,fund_source,code,name,allotment,obligation,disbursement) VALUES (2026,'GAS','CURRENT','5020109000','WAL record',22.10,10.05,5.01)",
    );
    expect(File('$sourcePath-wal').existsSync(), isTrue);
    final migrated = FinanceDatabase.open(
      path: '${temp.path}/flutter.sqlite',
      legacyPath: sourcePath,
    );
    final copied = migrated.rows(
      "SELECT allotment FROM budget_records WHERE code='5020109000'",
    );
    expect(copied.single['allotment'], 22.10);
    expect(source.rows('SELECT * FROM budget_records').length, 2);
    migrated.close();
    source.close();
    temp.deleteSync(recursive: true);
  });
  test(
    'an invalid legacy database never leaves a partial destination behind',
    () {
      final temp = Directory.systemTemp.createTempSync('ncsc-invalid-');
      final legacy = '${temp.path}/invalid.sqlite';
      File(legacy).writeAsStringSync('This is not a SQLite database.');
      final target = '${temp.path}/flutter.sqlite';
      expect(
        () => FinanceDatabase.open(path: target, legacyPath: legacy),
        throwsA(anything),
      );
      expect(File(target).existsSync(), isFalse);
      expect(File(legacy).readAsStringSync(), 'This is not a SQLite database.');
      temp.deleteSync(recursive: true);
    },
  );
  test(
    'account and records persist after closing and reopening the database',
    () async {
      final temp = Directory.systemTemp.createTempSync('ncsc-persistence-');
      final path = '${temp.path}/finance.sqlite';
      var db2 = FinanceDatabase.open(path: path);
      var s = FinanceStore(db2);
      await s.createOwner('Finance AO', 'ao', 'TestPassword2026');
      db2.connection.execute(
        "INSERT INTO programs(code,name,active) VALUES ('GAS','GAS',1)",
      );
      s.saveRecord(record());
      s.dispose();
      db2.close();
      db2 = FinanceDatabase.open(path: path);
      s = FinanceStore(db2);
      expect(s.needsAccount, isFalse);
      await s.signIn('ao', 'TestPassword2026');
      expect(s.records(manilaNow().year).single.balance, 75005);
      s.dispose();
      db2.close();
      temp.deleteSync(recursive: true);
    },
  );
